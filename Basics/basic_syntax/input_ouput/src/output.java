public class output {
    public static void main(String[] args) {
        //1.println() - prints the output in a new line
        System.out.println("Hello World");
        //2.print() - prints the output in the same line
        System.out.print("Hello World");
        //3.printf() - prints the output in a formatted way
        String a = "Hello World";
        System.out.printf("Hello %s", a);

    }
}
